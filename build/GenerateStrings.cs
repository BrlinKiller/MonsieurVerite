using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

/// <summary>
/// Writes a <c>Strings</c> property for each plain string in en-US.json and a method for each
/// string with placeholders.
/// </summary>
public class GenerateStrings : Task
{
    private static readonly Regex Entry =
        new Regex(@"""([A-Z][A-Z0-9_]*)""\s*:\s*""((?:[^""\\]|\\.)*)""");

    private static readonly Regex Placeholder = new Regex(@"\{([a-z][a-z0-9_]*)\}");

    [Required] public string Source { get; set; }

    [Required] public string Output { get; set; }

    [Required] public string Namespace { get; set; }

    public override bool Execute()
    {
        var code = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine($"namespace {Namespace};")
            .AppendLine()
            .AppendLine("public static partial class Strings")
            .AppendLine("{");

        foreach (Match entry in Entry.Matches(File.ReadAllText(Source)))
        {
            var key = entry.Groups[1].Value;
            var names = Placeholder.Matches(entry.Groups[2].Value).Cast<Match>()
                .Select(match => match.Groups[1].Value)
                .Distinct()
                .ToList();
            if (names.Count == 0)
            {
                code.AppendLine($"    public static string {key} => Text(\"{key}\");");
                continue;
            }

            var parameters = string.Join(", ", names.Select(name => $"object? @{name}"));
            var values = string.Join(", ", names.Select(name => $"(\"{name}\", @{name})"));
            code.AppendLine(
                $"    public static string {key}({parameters}) => Fill(\"{key}\", {values});");
        }

        File.WriteAllText(Output, code.AppendLine("}").ToString());
        return true;
    }
}
